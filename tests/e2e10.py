# البداية الفارغة، ومكتب المحامي (أنواع هرمية)، ونافذة الرفع الموحدة: python3 tests/e2e10.py (خادم على 8765)
import sys, os, pathlib
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from playwright.sync_api import sync_playwright
BASE='http://localhost:8765/index.html'; fails=[]
def check(n, c, x=''):
    print(('✓ ' if c else '✗ ')+n, x if not c else '')
    if not c: fails.append(n)
with sync_playwright() as p:
    b=p.chromium.launch(args=['--no-sandbox']); ctx=b.new_context(viewport={'width':390,'height':800},service_workers='block')
    page=ctx.new_page(); errs=[]; page.on('pageerror',lambda e:errs.append(str(e)))
    page.goto(BASE); page.wait_for_selector('.start-card')
    check('سطح مكتب جديد بلا تطبيقات افتراضية', page.locator('.app-card').count()==0 and page.evaluate("Store.db.registry.length")==0)
    page.wait_for_selector('.start-item'); n=page.locator('.start-item').count()
    check('البطاقة تعرض إضافات المتجر (%d)'%n, n>=8)
    check('زر المتجر ينبض', page.evaluate("document.getElementById('store-btn').classList.contains('pulse')"))
    page.locator('.start-item',has_text='مكتب المحامي').click(); page.wait_for_selector('.app-card')
    check('التثبيت بنقرة يضع الإضافة على السطح وتختفي البطاقة', page.locator('.app-card').count()==1 and page.locator('.start-card').count()==0 and not page.evaluate("document.getElementById('store-btn').classList.contains('pulse')"))
    page.locator('.app-card',has_text='مكتب المحامي').click(); page.wait_for_timeout(1800)
    fr=[f for f in page.frames if f!=page.main_frame][0]
    fr.evaluate("S.tab='cases';render()"); fr.wait_for_selector('.krow')
    check('شريط الأنواع الهرمي يظهر بجذوره', fr.locator('.krow .chip[data-k=\"مدنية\"]').count()==1)
    fr.evaluate("setTimeout(()=>editCase(),0)"); fr.wait_for_selector('.tpick')
    fr.locator('.tpick').click(); fr.wait_for_selector('.tpanel:not([hidden]) .kr')
    fr.locator('.tpanel .kr:has-text(\"مدنية\") [data-k=tg]').first.click()
    check('الطي والفتح يعملان', fr.locator('.tpanel .kr:has-text(\"عقارية\")').count()>=0)
    fr.locator('.tpanel .kr:has-text(\"مدنية\") [data-k=add]').first.click(); fr.fill('.tpanel [name=kv]','نزع ملكية'); fr.press('.tpanel [name=kv]','Enter')
    check('إضافة فرع جديد', fr.evaluate("kFlat(kinds()).some(r=>r.p.join(SEP)==='مدنية › نزع ملكية')"))
    fr.locator('.tpanel .kn',has_text='نزع ملكية').click()
    check('اختيار النوع يملأ الحقل', fr.evaluate("document.getElementById('f_kind').value")=='مدنية › نزع ملكية')
    fr.fill('#f_title','قضية اختبار'); fr.locator('form.frm button[type=submit]').click(); fr.wait_for_timeout(400)
    fr.evaluate("S.tab='cases';S.caseId=null;S.filter='all';render()")
    fr.locator('.krow .chip[data-k=\"مدنية\"]').click(); fr.wait_for_timeout(200)
    check('التصفية الهرمية: الأب يشمل الفرع', fr.locator('.list .cr').count()==1)
    check('صف الأبناء يظهر عند اختيار الأب', fr.locator('.krow').count()==2)
    fr.locator('.krow .chip[data-k=\"مدنية › عقارية\"]').click(); fr.wait_for_timeout(200)
    check('تصفية فرع آخر لا تُظهر القضية', fr.locator('.list .cr').count()==0)
    fr.locator('.krow .chip.on').last.click(); fr.wait_for_timeout(150)
    check('الضغط على المحدد يصعد درجة', fr.evaluate("S.kind")=='مدنية')
    fr.locator('[data-act=kinds]').click(); fr.wait_for_selector('#kp .kr')
    fr.locator('#kp .kr:has-text(\"نزع ملكية\") [data-k=ren]').click(); fr.fill('#kp .krn','مصادرة'); fr.press('#kp .krn','Enter')
    check('إعادة التسمية تحدّث قيمة القضية', fr.evaluate("DB.cases[0].kind")=='مدنية › مصادرة')
    fr.locator('#kp .kr:has-text(\"مصادرة\") [data-k=del]').click(); fr.locator('#kp .kr:has-text(\"مصادرة\") [data-k=del]').click()
    check('الحذف بخطوتين', not fr.evaluate("kFlat(kinds()).some(r=>r.n.name==='مصادرة')"))
    fr.evaluate("persist()"); page.wait_for_timeout(600); page.reload(); page.wait_for_selector('.app-card')
    page.locator('.app-card',has_text='مكتب المحامي').click(); page.wait_for_timeout(1800)
    fr=[f for f in page.frames if f!=page.main_frame][0]
    check('أنواعك المعدّلة تبقى بعد إعادة التحميل', fr.evaluate("kFlat(kinds()).every(r=>r.n.name!=='مصادرة') && kFlat(kinds()).some(r=>r.n.name==='مدنية')"))
    # ===== نافذة الإضافة الموحدة =====
    d=pathlib.Path('/tmp/up_t/proj'); (d/'src').mkdir(parents=True,exist_ok=True); (d/'.git').mkdir(exist_ok=True)
    (d/'a.txt').write_text('a'); (d/'src'/'b.js').write_text('b'); (d/'.git'/'x').write_text('x'); (d/'.DS_Store').write_text('x')
    page.goto(BASE); page.wait_for_selector('.app-card')
    page.evaluate("setTimeout(()=>{window.__r=undefined;Uploader.choose().then(r=>window.__r=r)},0)"); page.wait_for_selector('.up-dlg')
    check('زر واحد لملفات ومجلد', page.locator('.up-btns [data-u=files]').count()==1 and page.locator('.up-btns [data-u=dir]').count()==1)
    page.set_input_files('#up-d', str(d)); page.wait_for_timeout(200)
    check('مخلّفات النظام و.git تُتجاهل', page.locator('.up-list li').count()==2, page.inner_text('.up-sum'))
    page.click('[data-u=go]'); page.wait_for_timeout(200)
    check('تجاهل اسم المجلد الرئيسي', sorted(page.evaluate("window.__r.files.map(f=>f.path)"))==['a.txt','src/b.js'])
    page.evaluate("setTimeout(()=>{window.__r=undefined;Uploader.choose().then(r=>window.__r=r)},0)"); page.wait_for_selector('.up-dlg')
    page.set_input_files('#up-d', str(d)); page.uncheck('#up-strip'); page.click('[data-u=go]'); page.wait_for_timeout(200)
    check('إبقاء اسم المجلد عند إلغاء الخيار', sorted(page.evaluate("window.__r.files.map(f=>f.path)"))==['proj/a.txt','proj/src/b.js'])
    page.evaluate("setTimeout(()=>{window.__r=undefined;Uploader.choose().then(r=>window.__r=r)},0)"); page.wait_for_selector('.up-dlg')
    page.keyboard.press('Escape'); page.wait_for_timeout(150)
    check('Escape يغلق النافذة ويعيد null', page.evaluate("window.__r")is None and page.locator('.up-dlg').count()==0)
    check('لا أخطاء JS', not [e for e in errs if 'serviceWorker' not in e], str(errs[:2]))
    b.close()
print('ALL OK' if not fails else 'FAILED: %s'%fails); sys.exit(1 if fails else 0)
